# Ejercicio 10 Area y perimetro de un rectangulo 
# Solicitar el largo del terreno
largo = float(input("Ingrese largo del terreno: "))
# Solicitar el ancho del terreno
ancho = float(input("Ingrese ancho del terreno: "))
# Obtener el area del terreno
area = largo * ancho
# Obtener el perimetro del terreno
perimetro = 2 * (largo + ancho)
# Presentar los resultados obtenidos
print("El area del terreno es:", area)
print("El perimetro del terreno es:", perimetro)
